/// Generate a KDL policy draft from cross-validation results and capability profile.
///
/// If `project_hint` is provided, advisory comments are appended based on
/// static analysis of the project's dependencies and source code.
///
/// Live `tools/list` entries drive `args_schema` (W1) and CC / RIS comments (W2).
/// Blocking findings get `deny=#true`. RIS is advisory and never used by `run`.
///
/// `workload` carries the launch-target hashes the draft pins inside the
/// `server` block (`binary-hash` / `entrypoint-hash`, or the reason a target
/// cannot be bound). Pass `&WorkloadHashes::default()` to emit none.
pub fn generate_policy(
    result: &CrossValidationResult,
    capability: &CapabilityProfile,
    project_hint: Option<&crate::legislator::project_hints::ProjectHint>,
    tools: &[ToolDefinition],
    workload: &WorkloadHashes,
) -> String {
    // Build the tools section first: when every emitted tool is denied
    // (dispatcher-shaped servers where nothing could be grounded — F-10)
    // the draft head must say so, or the operator reads an all-deny
    // policy as a generation bug.
    let mut tools_out = String::new();
    let (ungrounded_tools, emitted_tools, tools_list_pinned) =
        build_tools_section(&mut tools_out, result, tools, workload);

    let mut out = String::new();

    out.push_str("// Policy Draft - Auto-generated by MCP Writ\n");
    out.push_str(&MarkerKind::Header.comment("all entries before deploying"));
    out.push('\n');
    if ungrounded_tools > 0 && ungrounded_tools == emitted_tools {
        // Every emitted tool lacks grounding — the dispatcher-shaped
        // case (guide §4.3, "Case C"). The note must say *why* that is,
        // so an all-deny draft reads as the expected shape instead of a
        // generation bug. The integrity bullet only claims the
        // tools-list-hash pin when one was actually emitted — a draft
        // built without live discovery carries no pin to rest on.
        let integrity_bullet = if tools_list_pinned {
            "//   - integrity rests on the tools-list-hash pin — the digest of the\n\
             //     tools/list that --live-discovery returned — so `check` and `run`\n\
             //     detect any later change in the advertised tool set;\n"
        } else {
            "//   - this draft carries no tools-list-hash pin — rerun with\n\
             //     --live-discovery, or add another reviewed integrity\n\
             //     measure, before relying on `check` and `run` to police\n\
             //     the advertised tool set;\n"
        };
        out.push_str(&format!(
            "// NOTE: {ungrounded_tools}/{emitted_tools} tools in this draft carry no \
             capability grounding — every\n\
             // discovered tool was emitted deny=#true. This is the dispatcher-shaped\n\
             // case: tool names are not bound to handlers as string literals — calls\n\
             // route through one entry point such as @server.call_tool() or\n\
             // setRequestHandler — so capability analysis (syscalls, strings,\n\
             // manifest) cannot be attributed per tool and no allowed/blocked\n\
             // verdict can be proven (guide §4.3, \"Case C\"). What that leaves\n\
             // to the operator:\n\
             //   - allow decisions are per tool: lift deny=#true only on tools you\n\
             //     have reviewed and keep; a kept tool needs side_effect and any\n\
             //     sub-policies by hand;\n\
             {integrity_bullet}\
             //   - on a server update, regenerate into a separate file\n\
             //     (`generate-policy --live-discovery`), diff it against this draft,\n\
             //     and merge after review (guide §8.2).\n\
             // examples/policies/ holds maintained starting points.\n"
        ));
    } else if ungrounded_tools > 0 {
        // Some tools are grounded and some are not — say how many, but
        // do not claim the whole draft is dispatcher-shaped.
        out.push_str(&format!(
            "// NOTE: {ungrounded_tools}/{emitted_tools} tools in this draft carry no \
             capability grounding —\n\
             // those were emitted deny=#true pending your review; each tool's REVIEW\n\
             // marker names the verdict that could not ground it. Lift deny=#true only\n\
             // on tools you have reviewed and keep.\n"
        ));
    }
    out.push_str("policy version=2\n");
    out.push('\n');
    out.push_str("// MCP passage rules default fail-closed: resources/prompts/\n");
    out.push_str("// completion/logging methods, server-originated requests, and MRTR\n");
    out.push_str("// `inputRequests` entries pass only with explicit `mcp` allow rules:\n");
    out.push_str("//   server \"<name>\" { mcp { allow \"elicitation/create\" } }\n");
    out.push_str("// tools/list + tools/call stay protocol machinery.\n\n");

    // defaults section
    out.push_str("defaults {\n");

    // filesystem
    build_fs_section(&mut out, result, capability, workload);

    // syscalls
    let interpreter_baseline = workload.interpreter.and_then(interpreter_syscall_baseline);
    build_syscalls_section(&mut out, result, capability, interpreter_baseline.as_ref());

    // network (advisory only — destinations are never inferred)
    build_network_section(&mut out, result, capability);

    // environment (commented-out candidates only — restriction stays)
    build_environment_section(&mut out, workload);

    out.push_str("}\n\n");

    // logging placeholder
    out.push_str("// === Logging ===\n");
    // No logging node needed in KDL minimal policy

    // server with tools
    out.push_str(&tools_out);

    // Project hints (advisory)
    if let Some(hint) = project_hint {
        build_project_hints_section(&mut out, hint);
    }

    out
}

/// `input_schema` copied verbatim only helps when the Auditor's evaluator
/// supports every keyword it carries — otherwise the first call would
/// fail at run time on a schema the operator never wrote. Unsupported
/// schemas are dropped from the draft and flagged for review instead of
/// being emitted unenforceably (PR-21). Returns `(review_comment,
/// kdl_property)`; at most one is non-empty.
fn args_schema_parts(tools: &[ToolDefinition], tool_name: &str) -> (String, String) {
    let Some(schema) = tools
        .iter()
        .find(|t| t.name == tool_name)
        .and_then(|t| t.input_schema.as_deref())
    else {
        return (String::new(), String::new());
    };
    let findings = crate::schema_spec::unsupported_schema_findings(schema);
    if !findings.is_empty() {
        let comment = format!(
            "    {}\n",
            MarkerKind::SchemaUnsupported.comment(&format!(
                "inputSchema uses unsupported schema features ({}); args_schema omitted — write a reviewed schema",
                escape_kdl_comment(&findings.join("; "))
            ))
        );
        return (comment, String::new());
    }
    (
        String::new(),
        format!(" args_schema=\"{}\"", escape_kdl_string(schema)),
    )
}

fn findings_by_tool(findings: &[ManifestFinding]) -> HashMap<String, Vec<ManifestFinding>> {
    let mut map: HashMap<String, Vec<ManifestFinding>> = HashMap::new();
    for finding in findings {
        map.entry(finding.tool_name.clone())
            .or_default()
            .push(finding.clone());
    }
    map
}

fn ris_by_tool(tools: &[ToolDefinition]) -> HashMap<String, RisScore> {
    tools
        .iter()
        .map(|t| (t.name.clone(), score_tool(t)))
        .collect()
}

fn tool_has_blocking(map: &HashMap<String, Vec<ManifestFinding>>, name: &str) -> bool {
    map.get(name)
        .map(|fs| fs.iter().any(|f| f.blocking))
        .unwrap_or(false)
}

fn manifest_comment_block(
    name: &str,
    findings_map: &HashMap<String, Vec<ManifestFinding>>,
    ris_map: &HashMap<String, RisScore>,
) -> String {
    let mut s = String::new();
    if let Some(findings) = findings_map.get(name) {
        for f in findings {
            if f.blocking {
                s.push_str(&format!(
                    "    {}\n",
                    MarkerKind::BlockedCapability.comment(&format!(
                        "{} ({}) — {}",
                        f.rule.as_str(),
                        f.severity.as_str(),
                        escape_kdl_comment(&f.detail)
                    ))
                ));
            } else {
                s.push_str(&format!(
                    "    // WARNING: {} ({}) — {}\n",
                    f.rule.as_str(),
                    f.severity.as_str(),
                    escape_kdl_comment(&f.detail)
                ));
            }
        }
    }
    if let Some(ris) = ris_map.get(name) {
        s.push_str(&format!("    // {}\n", ris.comment()));
    }
    s
}

/// Returns `(ungrounded, emitted, tools_list_pinned)` — how many tool
/// entries carry no capability grounding out of how many were emitted,
/// plus whether the `tools-list-hash` pin made it into the draft — so
/// the head can name the F-10 "all Case C" dispatcher shape, the
/// partial case, and the integrity anchor that actually exists.
fn build_tools_section(
    out: &mut String,
    result: &CrossValidationResult,
    discovered: &[ToolDefinition],
    workload: &WorkloadHashes,
) -> (usize, usize, bool) {
    let findings_map = findings_by_tool(&scan_manifest(discovered));
    let ris_map = ris_by_tool(discovered);

    let mut seen_tools: HashSet<String> = HashSet::new();
    let mut tools: Vec<String> = Vec::new();

    let denied: HashSet<String> = result
        .blocked
        .iter()
        .filter_map(|v| v.tool_name.clone())
        .collect();

    let mut warning_notes: HashMap<String, Vec<String>> = HashMap::new();
    for verdict in &result.warnings {
        if let Some(ref tool_name) = verdict.tool_name {
            warning_notes
                .entry(tool_name.clone())
                .or_default()
                .push(verdict.reason.clone());
        }
    }

    fn warning_comment_block(notes: Option<&Vec<String>>) -> String {
        let mut s = String::new();
        if let Some(notes) = notes {
            for reason in notes {
                s.push_str(&format!("    // WARNING: {}\n", escape_kdl_comment(reason)));
            }
        }
        s
    }

    // F-10 bookkeeping: tools emitted with no capability grounding —
    // Case-C verdicts and finding-only tools that never reached a
    // verdict. A draft where every tool is ungrounded gets the header
    // note: dispatcher-shaped servers otherwise look like a
    // generation bug. (Blocked and allowed tools have verdicts and
    // count as grounded.)
    let mut ungrounded = 0usize;

    // Deny candidates first so a mismatch is not emitted as an allowed tool.
    for verdict in &result.blocked {
        if let Some(ref tool_name) = verdict.tool_name {
            if !seen_tools.insert(tool_name.clone()) {
                continue;
            }
            let comments = manifest_comment_block(tool_name, &findings_map, &ris_map);
            let warnings = warning_comment_block(warning_notes.get(tool_name));
            let (schema_comment, schema_prop) = args_schema_parts(discovered, tool_name);
            tools.push(format!(
                "{comments}{warnings}{schema_comment}    {}\n    tool \"{}\" deny=#true{schema_prop}",
                MarkerKind::BlockedCapability
                    .comment(&escape_kdl_comment(&verdict.reason)),
                escape_kdl_string(tool_name),
            ));
        }
    }

    // Allowed tools (Case A)
    for verdict in &result.allowed {
        if let Some(ref tool_name) = verdict.tool_name {
            if denied.contains(tool_name) {
                continue;
            }
            if !seen_tools.insert(tool_name.clone()) {
                continue;
            }
            let comments = manifest_comment_block(tool_name, &findings_map, &ris_map);
            let warnings = warning_comment_block(warning_notes.get(tool_name));
            let (schema_comment, schema_prop) = args_schema_parts(discovered, tool_name);
            if tool_has_blocking(&findings_map, tool_name) {
                tools.push(format!(
                    "{comments}{warnings}{schema_comment}    tool \"{}\" deny=#true{schema_prop}",
                    escape_kdl_string(tool_name),
                ));
                continue;
            }
            let side_effect = determine_side_effect(result, tool_name);
            let perms: Vec<String> = result
                .allowed
                .iter()
                .filter(|v| v.tool_name.as_deref() == Some(tool_name))
                .map(|v| {
                    format!(
                        "Capability({}) ∩ Intent({}) [Case A]",
                        v.permission, v.permission
                    )
                })
                .collect();

            tools.push(format!(
                "{comments}{warnings}{schema_comment}    // Matched: {}\n    tool \"{}\" side_effect=\"{}\"{schema_prop}",
                perms.join(", "),
                escape_kdl_string(tool_name),
                side_effect,
            ));
        }
    }

    // Warning tools (Case C) that were not already emitted. A Case-C
    // verdict is "unproven", never "safe": emitting the tool bare would
    // let a call succeed without any capability match having been
    // established. Emit it denied with a REVIEW note — the operator
    // unblocks it only after judging the reason.
    for verdict in &result.warnings {
        if let Some(ref tool_name) = verdict.tool_name {
            if denied.contains(tool_name) {
                continue;
            }
            if !seen_tools.insert(tool_name.clone()) {
                continue;
            }
            let comments = manifest_comment_block(tool_name, &findings_map, &ris_map);
            let warnings = warning_comment_block(warning_notes.get(tool_name));
            let (schema_comment, schema_prop) = args_schema_parts(discovered, tool_name);
            if tool_has_blocking(&findings_map, tool_name) {
                tools.push(format!(
                    "{comments}{warnings}{schema_comment}    tool \"{}\" deny=#true{schema_prop}",
                    escape_kdl_string(tool_name),
                ));
                continue;
            }
            ungrounded += 1;
            tools.push(format!(
                "{comments}{warnings}{schema_comment}    {}\n    tool \"{}\" deny=#true{schema_prop}",
                MarkerKind::UnboundTool.comment(&escape_kdl_comment(&verdict.reason)),
                escape_kdl_string(tool_name),
            ));
        }
    }

    // Live tools with findings that cross-validation did not emit.
    for live in discovered {
        if !seen_tools.insert(live.name.clone()) {
            continue;
        }
        let some_findings = findings_map
            .get(&live.name)
            .map(|fs| !fs.is_empty())
            .unwrap_or(false);
        if !some_findings {
            continue;
        }
        let comments = manifest_comment_block(&live.name, &findings_map, &ris_map);
        let (schema_comment, schema_prop) = args_schema_parts(discovered, &live.name);
        if tool_has_blocking(&findings_map, &live.name) {
            tools.push(format!(
                "{comments}{schema_comment}    tool \"{}\" deny=#true{schema_prop}",
                escape_kdl_string(&live.name),
            ));
        } else {
            // Findings without a capability verdict — unproven, not
            // proven safe: emit denied so an operator must review the
            // tool before it can be called.
            ungrounded += 1;
            tools.push(format!(
                "{comments}{schema_comment}    {}\n    tool \"{}\" deny=#true{schema_prop}",
                MarkerKind::UnboundTool.comment("manifest findings without a capability verdict"),
                escape_kdl_string(&live.name),
            ));
        }
    }

    let mut tools_list_pinned = false;
    if !tools.is_empty() || !discovered.is_empty() || workload.has_content() {
        out.push_str("// === Tools ===\n");
        out.push_str("server \"auto-generated\" {\n");
        emit_workload_hashes(out, workload);
        if !discovered.is_empty() {
            match hash_tools_list(discovered) {
                Ok(digest) => {
                    tools_list_pinned = true;
                    out.push_str(
                        "    // mcp-guard-tools-list-v4 — re-pin after upgrading from v3\n",
                    );
                    out.push_str(&format!(
                        "    tools-list-hash \"{}\"\n",
                        escape_kdl_string(&digest)
                    ));
                }
                Err(e) => {
                    // Fail visible: the draft must not silently lose its
                    // tools-list pin. The reviewer must fix the offending
                    // field and regenerate.
                    out.push_str(&format!(
                        "    // ERROR: tools-list-hash could not be computed ({})\n",
                        escape_kdl_comment(&e)
                    ));
                }
            }
        }
        for tool_entry in &tools {
            out.push_str(tool_entry);
            out.push('\n');
        }
        out.push_str("}\n");
    }

    // F-10 bookkeeping for the draft head: `ungrounded` entries carry no
    // capability grounding (all Case C / verdict-less). `ungrounded ==
    // tools.len()` is the dispatcher shape; a smaller nonzero count is
    // the partial case the head also names.
    (ungrounded, tools.len(), tools_list_pinned)
}

/// Emit `binary-hash` / `entrypoint-hash` inside the `server` block, before
/// `tools-list-hash`. The hashes pin this host's files, so two REVIEW lines
/// tell the operator to recompute them on the deployment host and to
/// regenerate the draft when the server or its interpreter is updated.
/// A launch target that cannot be bound emits no hash line; its reason is
/// recorded as a comment instead.
fn emit_workload_hashes(out: &mut String, workload: &WorkloadHashes) {
    if workload.binary.is_some() || workload.entrypoint.is_some() {
        out.push_str(&format!(
            "    {}\n",
            MarkerKind::HashPinHost.comment(
                "workload hashes pin this host's files — recompute them on the deployment host"
            )
        ));
        out.push_str(&format!(
            "    {}\n",
            MarkerKind::RegenerateOnUpdate
                .comment("regenerate this draft when the server or its interpreter is updated")
        ));
        if let Some(ref binary) = workload.binary {
            out.push_str(&format!(
                "    binary-hash \"{}\" target=\"{}\"\n",
                escape_kdl_string(&binary.hash_value),
                escape_kdl_string(&binary.target)
            ));
        }
        if let Some(ref entrypoint) = workload.entrypoint {
            out.push_str(&format!(
                "    entrypoint-hash \"{}\" target=\"{}\"\n",
                escape_kdl_string(&entrypoint.hash_value),
                escape_kdl_string(&entrypoint.target)
            ));
        }
    }
    for reason in &workload.unbound_reasons {
        out.push_str(&format!(
            "    {}\n",
            MarkerKind::UnboundWorkload.comment(&escape_kdl_comment(reason))
        ));
    }
}

/// Determine side_effect value for a tool based on its permissions.
fn determine_side_effect(result: &CrossValidationResult, tool_name: &str) -> &'static str {
    let tool_perms: Vec<&Permission> = result
        .allowed
        .iter()
        .filter(|v| v.tool_name.as_deref() == Some(tool_name))
        .map(|v| &v.permission)
        .collect();

    if tool_perms.contains(&&Permission::ProcessExec) {
        "execute"
    } else if tool_perms.contains(&&Permission::FileWrite) {
        "write"
    } else if tool_perms.contains(&&Permission::NetworkOutbound) {
        "network"
    } else {
        "read_only"
    }
}

/// Build the filesystem sub-section inside defaults.
fn build_fs_section(
    out: &mut String,
    result: &CrossValidationResult,
    capability: &CapabilityProfile,
    workload: &WorkloadHashes,
) {
    out.push_str("    // === Filesystem ===\n");
    out.push_str("    filesystem {\n");
    out.push_str(
        "        // Overlay beats explicit allow. TOCTOU after Auditor check is Warden's job.\n",
    );
    out.push_str("        secret-overlay #true\n");

    // Directory grants already emitted from binary string analysis — a
    // `/<dir>/**` line covers the interpreter seeds under it, so the
    // seed pass skips what these lines already grant. Each entry keeps
    // its mode: a read grant cannot cover a write-needed seed.
    let mut granted: Vec<(PathBuf, &'static str)> = Vec::new();
    for path in &capability.strings.paths {
        if path.starts_with("/usr/lib")
            || path.starts_with("/etc/ssl")
            || path.starts_with("/etc/pki")
            || path.starts_with("/lib")
        {
            let glob = if path.contains('.') {
                path.clone()
            } else {
                granted.push((PathBuf::from(path), "read"));
                format!("{path}/**")
            };
            out.push_str(&format!(
                "        allow \"{}\" mode=\"read\"\n",
                escape_kdl_string(&glob)
            ));
        }
    }

    build_runtime_seed_grants(out, workload, &mut granted);

    let has_fs = result
        .allowed
        .iter()
        .any(|v| v.permission == Permission::FileRead || v.permission == Permission::FileWrite);
    if has_fs {
        out.push_str("        // Paths derived from binary string analysis\n");
    }

    out.push_str("    }\n");
}

/// One interpreter-derived filesystem grant the draft seeds: the
/// directory to allow, the Landlock mode, and the fact it was derived
/// from (emitted with the line so the operator can trim it back).
struct SeedGrant {
    dir: PathBuf,
    mode: &'static str,
    origin: SeedOrigin,
}

/// Where a seeded grant was derived from — the `// seeded from …`
/// comment's content and the `// REVIEW: runtime-seed:` detail.
enum SeedOrigin {
    /// The resolved `argv[0]` image the `binary-hash` pin names —
    /// grants for the executable's directory and install prefix.
    ResolvedExe(PathBuf),
    /// `argv[0]` — or a `#!`-selected interpreter — spelled before
    /// symlink canonicalization: a venv or shim's own layout.
    SpelledExe(PathBuf),
    /// The resolved payload — grants for the package tree the
    /// payload's imports resolve from.
    Payload(PathBuf),
    /// The `home=` line of a venv's `pyvenv.cfg` — the base
    /// interpreter prefix a copied `python.exe` does not reveal.
    VenvHome(PathBuf),
    /// The shared runtime baseline file's documented host paths
    /// (`examples/policies/runtime/<rt>.kdl`) — the documented list is
    /// Linux-only, so the variant exists only where it is constructed.
    #[cfg(target_os = "linux")]
    RuntimeFile(&'static str),
}

impl SeedOrigin {
    fn comment(&self) -> String {
        let (label, detail) = match self {
            Self::ResolvedExe(p) => ("resolved interpreter", p.display().to_string()),
            Self::SpelledExe(p) => ("launch argv0", p.display().to_string()),
            Self::Payload(p) => ("resolved payload", p.display().to_string()),
            Self::VenvHome(p) => ("pyvenv.cfg home", p.display().to_string()),
            #[cfg(target_os = "linux")]
            Self::RuntimeFile(f) => ("runtime baseline", (*f).to_string()),
        };
        format!("// seeded from {}: {}", label, escape_kdl_comment(&detail))
    }

    fn detail(&self) -> &'static str {
        match self {
            Self::ResolvedExe(_) => {
                "install prefix of the resolved interpreter — keep only if \
                 the runtime loads under it"
            }
            Self::SpelledExe(_) => {
                "prefix of the argv0-spelled interpreter — a venv or shim \
                 layout the resolved pin does not show"
            }
            Self::Payload(_) => {
                "package tree the payload's imports resolve from — keep \
                 what the server loads"
            }
            Self::VenvHome(_) => {
                "base interpreter prefix a venv's pyvenv.cfg names — the \
                 real standard library lives there"
            }
            #[cfg(target_os = "linux")]
            Self::RuntimeFile(_) => {
                "path the shared runtime baseline lists for this \
                 interpreter — delete what the workload does not read"
            }
        }
    }
}

/// True when `dir` is already covered by a grant emitted earlier —
/// equal to it or inside its subtree (a Landlock grant covers the
/// subtree; the SBPL/DACL emitters map directories the same way) *and*
/// that grant's mode covers what the new grant needs (`"write"` is
/// read+write, so it covers either need; `"read"` covers only a read
/// need — a read grant must not suppress a write-needed seed like
/// `/dev/null`). Both sides canonicalize when they exist so a `/lib`
/// symlink and its `/usr/lib` target dedupe.
fn grant_covered(dir: &Path, granted: &[(PathBuf, &'static str)], need: &'static str) -> bool {
    let canon = std::fs::canonicalize(dir).unwrap_or_else(|_| dir.to_path_buf());
    granted.iter().any(|(g, mode)| {
        let mode_covers = *mode == "write" || need == "read";
        let base = std::fs::canonicalize(g).unwrap_or_else(|_| g.clone());
        mode_covers && (canon == base || canon.starts_with(&base))
    })
}

/// The `home =` line of a `pyvenv.cfg` names the base interpreter
/// prefix — needed where the venv interpreter is a copy (Windows
/// `Scripts\python.exe`) rather than a symlink the resolved pin can
/// follow.
fn pyvenv_home(venv_dir: &Path) -> Option<PathBuf> {
    let text = std::fs::read_to_string(venv_dir.join("pyvenv.cfg")).ok()?;
    for line in text.lines() {
        if let Some(rest) = line.trim().strip_prefix("home")
            && let Some(value) = rest.trim_start().strip_prefix('=')
        {
            return Some(PathBuf::from(value.trim()));
        }
    }
    None
}

/// Read grants grounded in the resolved launch paths — the same class
/// of argv fact as the interpreter seccomp baseline, so the seed is
/// unconditional like that baseline (D-7): no flag gate, every line
/// carries provenance and a `runtime-seed` REVIEW so `check` lists
/// what the operator still owes.
fn build_runtime_seed_grants(
    out: &mut String,
    workload: &WorkloadHashes,
    granted: &mut Vec<(PathBuf, &'static str)>,
) {
    let Some(interpreter) = workload.interpreter else {
        return;
    };
    let mut grants: Vec<SeedGrant> = Vec::new();

    // The executable's directory and its parent (the install prefix):
    // shared libraries and runtime data load from under the prefix.
    // Run it for the resolved image and again for the argv0/shebang
    // spelling — a venv `bin/python` symlink resolves away from the
    // tree the interpreter reads `pyvenv.cfg` and site-packages from.
    for (exe, ctor) in [
        (
            workload.interpreter_path.as_deref(),
            SeedOrigin::ResolvedExe as fn(PathBuf) -> SeedOrigin,
        ),
        (
            workload.spelled_path.as_deref(),
            SeedOrigin::SpelledExe as fn(PathBuf) -> SeedOrigin,
        ),
    ] {
        let Some(exe) = exe else { continue };
        if let Some(dir) = exe.parent() {
            if dir.parent().is_some() {
                grants.push(SeedGrant {
                    dir: dir.to_path_buf(),
                    mode: "read",
                    origin: ctor(exe.to_path_buf()),
                });
            }
            if let Some(prefix) = dir.parent()
                && prefix.parent().is_some()
            {
                grants.push(SeedGrant {
                    dir: prefix.to_path_buf(),
                    mode: "read",
                    origin: ctor(exe.to_path_buf()),
                });
            }
        }
    }

    // The package tree the payload's imports resolve from.
    if let Some(payload) = workload.payload_path.as_deref() {
        match interpreter {
            InterpreterKind::Node | InterpreterKind::Npx => {
                // Nearest `node_modules` the payload sits under → its
                // parent (the package root covering `package.json` and
                // sibling trees); otherwise the nearest ancestor holding
                // `package.json` — a project-local entrypoint that never
                // reached a node_modules layout.
                if let Some(root) = payload
                    .ancestors()
                    .find(|a| a.file_name().is_some_and(|n| n == "node_modules"))
                    .and_then(|nm| nm.parent())
                {
                    grants.push(SeedGrant {
                        dir: root.to_path_buf(),
                        mode: "read",
                        origin: SeedOrigin::Payload(payload.to_path_buf()),
                    });
                } else if let Some(pkg) = payload
                    .ancestors()
                    .find(|a| a.join("package.json").is_file())
                {
                    grants.push(SeedGrant {
                        dir: pkg.to_path_buf(),
                        mode: "read",
                        origin: SeedOrigin::Payload(payload.to_path_buf()),
                    });
                }
            }
            InterpreterKind::Python => {
                // A payload inside `site-packages`/`dist-packages` —
                // the same tree holds the server's installed
                // dependencies, so the payload dir alone is not enough.
                if let Some(site) = payload.ancestors().find(|a| {
                    a.file_name()
                        .is_some_and(|n| n == "site-packages" || n == "dist-packages")
                }) {
                    grants.push(SeedGrant {
                        dir: site.to_path_buf(),
                        mode: "read",
                        origin: SeedOrigin::Payload(payload.to_path_buf()),
                    });
                }
            }
        }
        // The payload's own directory — sibling modules and resources
        // resolve relative to it.
        if let Some(dir) = payload.parent() {
            grants.push(SeedGrant {
                dir: dir.to_path_buf(),
                mode: "read",
                origin: SeedOrigin::Payload(payload.to_path_buf()),
            });
        }
    }

    // Python: the venv / site-packages prefix — `pyvenv.cfg` above a
    // `bin/` or `Scripts/` ancestor names the venv root, and its
    // `home=` line names the base interpreter prefix a copied
    // `python.exe` (a Windows venv) does not reveal.
    if matches!(interpreter, InterpreterKind::Python) {
        for (base, ctor) in [
            (
                workload.spelled_path.as_deref(),
                SeedOrigin::SpelledExe as fn(PathBuf) -> SeedOrigin,
            ),
            (
                workload.interpreter_path.as_deref(),
                SeedOrigin::ResolvedExe as fn(PathBuf) -> SeedOrigin,
            ),
        ] {
            let Some(base) = base else { continue };
            // `pyvenv.cfg` lives in the venv root — beside the exe or
            // one level above its `bin/`/`Scripts/` directory. Anything
            // higher cannot be a venv root, so the lookup stays within
            // those two directories and a stray config further up the
            // tree is not mistaken for one.
            let dir = base.parent();
            for anc in [dir, dir.and_then(Path::parent)].into_iter().flatten() {
                if !anc.join("pyvenv.cfg").is_file() {
                    continue;
                }
                grants.push(SeedGrant {
                    dir: anc.to_path_buf(),
                    mode: "read",
                    origin: ctor(base.to_path_buf()),
                });
                // The `home=` line is operator-controlled config text —
                // only an absolute path that names a directory with a
                // parent is a meaningful grant. `home` lands before its
                // parent prefix, mirroring the exe dir→prefix pair, so
                // the line the config actually names carries the
                // provenance comment.
                if let Some(home) = pyvenv_home(anc)
                    && home.is_absolute()
                    && home.parent().is_some()
                {
                    grants.push(SeedGrant {
                        dir: home.clone(),
                        mode: "read",
                        origin: SeedOrigin::VenvHome(home.clone()),
                    });
                    if let Some(prefix) = home.parent()
                        && prefix.parent().is_some()
                    {
                        grants.push(SeedGrant {
                            dir: prefix.to_path_buf(),
                            mode: "read",
                            origin: SeedOrigin::VenvHome(home),
                        });
                    }
                }
                break;
            }
        }
    }

    // Documented host paths the runtime needs on Linux, when present —
    // the shared baseline file's own list, not an inference.
    #[cfg(target_os = "linux")]
    {
        let runtime_file = match interpreter {
            InterpreterKind::Node | InterpreterKind::Npx => "examples/policies/runtime/node.kdl",
            InterpreterKind::Python => "examples/policies/runtime/python.kdl",
        };
        let mut dirs: Vec<&str> = vec![
            "/usr/lib",
            "/lib",
            "/lib64",
            "/usr/local/lib",
            "/etc/ssl",
            "/proc",
        ];
        // python.kdl: zone-aware servers need the host TZDB search
        // path — a denied lookup aborts rather than falling back.
        if matches!(interpreter, InterpreterKind::Python) {
            dirs.push("/usr/share/zoneinfo");
        }
        for dir in dirs {
            if Path::new(dir).exists() {
                grants.push(SeedGrant {
                    dir: PathBuf::from(dir),
                    mode: "read",
                    origin: SeedOrigin::RuntimeFile(runtime_file),
                });
            }
        }
        // Interpreters open /dev/null O_RDWR (libuv stream setup,
        // subprocess stdio) — a read grant alone cannot satisfy the
        // write half.
        if Path::new("/dev/null").exists() {
            grants.push(SeedGrant {
                dir: PathBuf::from("/dev/null"),
                mode: "write",
                origin: SeedOrigin::RuntimeFile(runtime_file),
            });
        }
    }

    let mut seeded = false;
    for grant in grants {
        // Dedupe against earlier grants as they land — the spelled
        // interpreter resolves to the same directories as the resolved
        // image whenever no venv or shim intervenes.
        if grant_covered(&grant.dir, granted, grant.mode) {
            continue;
        }
        if !seeded {
            out.push_str("        // === Runtime defaults ===\n");
            out.push_str(
                "        // Read paths the resolved interpreter layout needs — grounded in\n",
            );
            out.push_str(
                "        // the launch argv like the seeded syscall baseline. The server's\n",
            );
            out.push_str(
                "        // data/work directories cannot be inferred — grant those by hand.\n",
            );
            seeded = true;
        }
        granted.push((grant.dir.clone(), grant.mode));
        out.push_str(&format!("        {}\n", grant.origin.comment()));
        out.push_str(&format!(
            "        {}\n",
            MarkerKind::RuntimeSeed.comment(grant.origin.detail())
        ));
        out.push_str(&format!(
            "        allow \"{}\" mode=\"{}\"\n",
            escape_kdl_string(&grant.dir.to_string_lossy()),
            grant.mode
        ));
    }
}

/// The `environment` draft — commented-out candidates only. The child
/// environment is restricted by default, so enabling names stays the
/// operator's act and the draft itself adds no live `environment`
/// block (fail-closed). Candidate names are a fixed per-runtime list;
/// the generator never scans the parent environment to collect names,
/// and values are never inferred (D-7).
fn build_environment_section(out: &mut String, workload: &WorkloadHashes) {
    let Some(interpreter) = workload.interpreter else {
        return;
    };
    let candidates: &[&str] = match interpreter {
        InterpreterKind::Node | InterpreterKind::Npx => &[
            "NODE_EXTRA_CA_CERTS",
            "SSL_CERT_FILE",
            "HTTP_PROXY",
            "HTTPS_PROXY",
            "NO_PROXY",
        ],
        InterpreterKind::Python => &[
            "SSL_CERT_FILE",
            "REQUESTS_CA_BUNDLE",
            "HTTP_PROXY",
            "HTTPS_PROXY",
            "NO_PROXY",
            "PYTHONUTF8",
            "PYTHONIOENCODING",
            "TZ",
        ],
    };
    out.push_str("    // === Environment ===\n");
    out.push_str("    // The spawned server receives a restricted environment: names are\n");
    out.push_str("    // copied from the parent only when an `allow` lists them — the\n");
    out.push_str("    // draft enables nothing itself.\n");
    out.push_str(&format!(
        "    {} enable only the names this server reads\n",
        MarkerKind::RuntimeSeed.comment_head()
    ));
    out.push_str(&format!(
        "    // environment {{ allow {} }}\n",
        candidates
            .iter()
            .map(|n| format!("\"{n}\""))
            .collect::<Vec<_>>()
            .join(" ")
    ));
}

/// The interpreter's shared seccomp baseline, compiled in from the same
/// `examples/policies/runtime/<name>.kdl` that host policies `extends` —
/// a generated draft stays self-contained wherever it is saved, so the
/// baseline travels with the binary rather than the checkout. Returns
/// `(source label, allow names)`; `None` when the embedded file cannot
/// yield a list (in-repo content — that would be a build bug, not an
/// operator error, and the draft falls back to REVIEW comments).
fn interpreter_syscall_baseline(
    interpreter: InterpreterKind,
) -> Option<(&'static str, Vec<String>)> {
    let (label, text) = match interpreter {
        InterpreterKind::Node | InterpreterKind::Npx => (
            "examples/policies/runtime/node.kdl",
            include_str!("../../examples/policies/runtime/node.kdl"),
        ),
        InterpreterKind::Python => (
            "examples/policies/runtime/python.kdl",
            include_str!("../../examples/policies/runtime/python.kdl"),
        ),
    };
    crate::policy::kdl_loader::parse_kdl_policy(text)
        .ok()
        .map(|p| (label, p.syscalls.allowed))
        .filter(|(_, names)| !names.is_empty())
}

/// Build the syscalls sub-section inside defaults.
fn build_syscalls_section(
    out: &mut String,
    result: &CrossValidationResult,
    capability: &CapabilityProfile,
    interpreter_baseline: Option<&(&'static str, Vec<String>)>,
) {
    out.push_str("    // === Syscalls ===\n");
    out.push_str("    syscalls {\n");

    // Surface the analysis target so the reviewer knows which syscall table
    // the allow names below were resolved against.
    let t = &capability.analysis.target;
    out.push_str(&format!(
        "        // Target: format={} isa={} abi={} endianness={}\n",
        t.format.as_str(),
        t.isa.as_str(),
        t.abi.as_str(),
        t.endianness.as_str(),
    ));

    // Fail-visible: when syscall analysis did not complete, the allowlist
    // below is built on incomplete data and must be reviewed manually.
    let sc_state = &capability.analysis.syscalls;
    if sc_state.status != crate::inspector::target::AnalysisStatus::Analyzed {
        let reason = sc_state.reason.map(|r| r.as_str()).unwrap_or("none");
        let detail = sc_state
            .detail
            .as_deref()
            .map(|d| format!(" — {}", escape_kdl_comment(d)))
            .unwrap_or_default();
        out.push_str(&format!(
            "        {} syscall analysis status={} reason={}{}\n",
            MarkerKind::SyscallAnalysis.comment_head(),
            sc_state.status.as_str(),
            reason,
            detail,
        ));
        out.push_str(&format!(
            "        {} allowlist below may be incomplete; do not deploy without manual review\n",
            MarkerKind::SyscallAnalysis.comment_head()
        ));
    }

    // The `allow` entries below are Linux seccomp names, emitted only
    // for a confirmed Linux ABI. Darwin `x16` values resolve against XNU
    // tables (BSD syscalls and Mach traps in separate namespaces), and an
    // undetermined ABI means the numbering convention itself is unknown —
    // neither may feed a Linux allowlist, so both get review comments.
    // A blocked verdict only vetoes a syscall class when no allowed verdict
    // claims the same permission — `cross_validate_source` emits per-tool
    // verdicts, so one tool's Case-B block must not strip the syscalls a
    // Case-A tool legitimately needs (the process-wide seccomp list cannot
    // express "allowed for this tool only", and `build_network_section`
    // keys its advisory off `result.allowed` the same way).
    let allowed_perms: HashSet<&Permission> =
        result.allowed.iter().map(|v| &v.permission).collect();
    let blocked_perms: Vec<&Permission> = result
        .blocked
        .iter()
        .map(|v| &v.permission)
        .filter(|p| !allowed_perms.contains(p))
        .collect();

    if t.abi == crate::inspector::target::SyscallAbi::Linux {
        let mut allowed_set: Vec<&str> = BASE_SYSCALLS.to_vec();

        for sc in &capability.syscalls {
            if let Some(ref name) = sc.syscall_name {
                let name_str = name.as_str();
                if is_syscall_blocked(name_str, &blocked_perms) {
                    continue;
                }
                if !allowed_set.contains(&name_str) {
                    allowed_set.push(name_str);
                }
            }
        }

        // A launch that pairs native analysis with a modeled interpreter
        // still needs the interpreter's runtime syscalls — merge the shared
        // baseline under the same blocked-permission filter.
        if let Some((_, baseline_names)) = interpreter_baseline {
            for name in baseline_names {
                let name_str = name.as_str();
                if is_syscall_blocked(name_str, &blocked_perms) {
                    continue;
                }
                if !allowed_set.contains(&name_str) {
                    allowed_set.push(name_str);
                }
            }
        }

        // Emit allow lines in groups of ~6 for readability
        for chunk in allowed_set.chunks(6) {
            let args: Vec<String> = chunk
                .iter()
                .map(|s| format!("\"{}\"", escape_kdl_string(s)))
                .collect();
            out.push_str(&format!("        allow {}\n", args.join(" ")));
        }

        // REVIEW comments for blocked syscalls — skip verdicts whose
        // permission class another tool was allowed: those syscalls were
        // kept in the allowlist above and "blocked" would misreport them.
        for verdict in &result.blocked {
            if allowed_perms.contains(&verdict.permission) {
                continue;
            }
            match verdict.permission {
                Permission::ProcessExec => {
                    for sc in &capability.syscalls {
                        if let Some(ref name) = sc.syscall_name
                            && ["execve", "execveat", "fork", "vfork", "clone", "clone3"]
                                .contains(&name.as_str())
                        {
                            out.push_str(&format!(
                                "        {} {} detected in binary but blocked (excess capability)\n",
                                MarkerKind::SyscallBlocked.comment_head(),
                                escape_kdl_comment(name)
                            ));
                        }
                    }
                }
                Permission::NetworkOutbound => {
                    for sc in &capability.syscalls {
                        if let Some(ref name) = sc.syscall_name
                            && NETWORK_SYSCALLS.contains(&name.as_str())
                        {
                            out.push_str(&format!(
                                "        {} {} detected in binary but blocked (excess capability)\n",
                                MarkerKind::SyscallBlocked.comment_head(),
                                escape_kdl_comment(name)
                            ));
                        }
                    }
                }
                _ => {}
            }
        }
    } else if let Some((baseline_src, names)) = interpreter_baseline {
        // Interpreted payload: the analyzed object is source text, not an
        // ELF, so there is no syscall table to resolve — but the runtime
        // that executes it has a known seccomp footprint. Emitting the
        // shared baseline keeps the draft enforceable instead of an
        // allow-nothing list that refuses the launch outright. Baseline
        // names pass the same blocked-permission filter as analyzed
        // syscalls — a denied capability class must not re-enter through
        // the baseline (e.g. `execve` under a blocked ProcessExec, or
        // `socket` under a blocked NetworkOutbound).
        let usable: Vec<&str> = names
            .iter()
            .map(String::as_str)
            .filter(|n| !is_syscall_blocked(n, &blocked_perms))
            .collect();
        out.push_str("        // Interpreted workload: no ELF syscall table exists for a source\n");
        out.push_str(&format!(
            "        // payload — seeded the shared interpreter baseline from {}\n",
            escape_kdl_comment(baseline_src)
        ));
        for chunk in usable.chunks(6) {
            let args: Vec<String> = chunk
                .iter()
                .map(|s| format!("\"{}\"", escape_kdl_string(s)))
                .collect();
            out.push_str(&format!("        allow {}\n", args.join(" ")));
        }
        let dropped: Vec<&str> = names
            .iter()
            .map(String::as_str)
            .filter(|n| is_syscall_blocked(n, &blocked_perms))
            .collect();
        if !dropped.is_empty() {
            out.push_str(&format!(
                "        {} baseline entries dropped by blocked permissions: {}\n",
                MarkerKind::BaselineDropped.comment_head(),
                escape_kdl_comment(&dropped.join(", "))
            ));
        }
        out.push_str(&format!(
            "        {} covers interpreter runtime needs; workload-specific\n",
            MarkerKind::InterpreterBaseline.comment_head()
        ));
        out.push_str("        // syscalls may still be missing — `unknown syscall` or EPERM in\n");
        out.push_str("        // stderr or the audit log names what to add. A child `syscalls`\n");
        out.push_str("        // allow REPLACES this whole list — it does not append.\n");
    } else {
        out.push_str(&format!(
            "        {} target uses a non-Linux syscall ABI — the entries below are\n",
            MarkerKind::NonLinuxAbi.comment_head()
        ));
        out.push_str("        // informational only; they are NOT Linux seccomp names and no\n");
        out.push_str("        // `allow` lines were emitted for this target.\n");
        for sc in capability.syscalls.iter().take(40) {
            let num = sc
                .syscall_number
                .map(|n| n.to_string())
                .unwrap_or_else(|| "?".to_string());
            out.push_str(&format!(
                "        //   {} ({}) kind={}\n",
                escape_kdl_comment(sc.syscall_name.as_deref().unwrap_or("unknown")),
                num,
                sc.kind.as_str(),
            ));
        }
        if capability.syscalls.len() > 40 {
            out.push_str("        //   ... (truncated)\n");
        }
    }

    out.push_str("    }\n");
}

/// Build the network sub-section inside defaults — advisory comments
/// only, never a `network` node. Destinations and ports cannot be
/// inferred from syscall evidence, so the draft keeps the deny-all
/// posture and spells the allow syntax for the reviewer instead of
/// emitting a guessed rule. Datagram-family syscalls additionally get
/// a note that they are UDP-compatible but not proof that UDP is
/// required: `proto="udp"` is declared only by a human — it is never
/// inferred, and a TCP allow never covers it.
fn build_network_section(
    out: &mut String,
    result: &CrossValidationResult,
    capability: &CapabilityProfile,
) {
    if !result
        .allowed
        .iter()
        .any(|v| v.permission == Permission::NetworkOutbound)
    {
        return;
    }
    out.push_str("    // === Network ===\n");
    out.push_str(&format!(
        "    {} NetworkOutbound capability detected — deny-all stays the\n",
        MarkerKind::NetworkOutbound.comment_head()
    ));
    out.push_str("    // posture; declare each destination and port explicitly, e.g.\n");
    out.push_str("    //   network { allow host=\"<ip-or-name>\" proto=\"tcp\" port=<port> }\n");
    // The same syscall name can recur across call sites — the advisory
    // lists each sanitized name once, in first-seen order.
    let mut seen_datagram: HashSet<String> = HashSet::new();
    let datagram: Vec<String> = capability
        .syscalls
        .iter()
        .filter_map(|sc| sc.syscall_name.as_deref())
        .filter(|n| {
            [
                "sendto", "sendmsg", "sendmmsg", "recvfrom", "recvmsg", "recvmmsg",
            ]
            .contains(n)
        })
        .map(escape_kdl_comment)
        .filter(|n| seen_datagram.insert(n.clone()))
        .collect();
    if !datagram.is_empty() {
        out.push_str(&format!(
            "    {} datagram syscalls ({}) — compatible with UDP but\n",
            MarkerKind::Datagram.comment_head(),
            datagram.join(", ")
        ));
        out.push_str("    // not proof that UDP is required; UDP/QUIC is never inferred,\n");
        out.push_str("    // and a TCP allow never covers it. If the workload needs UDP,\n");
        out.push_str("    // declare it explicitly, e.g.\n");
        out.push_str(
            "    //   network { allow host=\"<ip-or-name>\" proto=\"udp\" port=<port> }\n",
        );
        out.push_str("    // On Linux `run`, UDP grants are enforced only on the namespaced\n");
        out.push_str("    // route — `--linux-mechanism auto` (the default) selects it when the\n");
        out.push_str("    // host probe passes; the native route and the in-guest container\n");
        out.push_str("    // runner refuse a UDP allow rather than run it unenforced.\n");
    }
}

/// Build advisory project hints section from static analysis results.
fn build_project_hints_section(
    out: &mut String,
    hint: &crate::legislator::project_hints::ProjectHint,
) {
    if hint.detected_permissions.is_empty() {
        return;
    }
    out.push_str("\n// === Project Hints (advisory) ===\n");
    out.push_str(&format!(
        "// Project type: {}\n",
        escape_kdl_comment(&hint.project_type.to_string())
    ));
    out.push_str(&format!(
        "// Confidence: {}\n",
        escape_kdl_comment(hint.confidence_summary.as_str())
    ));
    for h in &hint.detected_permissions {
        out.push_str(&format!(
            "// Hint: {} ({}, {}) — {}\n",
            escape_kdl_comment(h.permission.as_str()),
            escape_kdl_comment(h.confidence.as_str()),
            escape_kdl_comment(&h.source.to_string()),
            escape_kdl_comment(&h.evidence)
        ));
    }
}

/// Check if a syscall name corresponds to any blocked permission category.
fn is_syscall_blocked(name: &str, blocked_perms: &[&Permission]) -> bool {
    if blocked_perms.contains(&&Permission::ProcessExec)
        && ["execve", "execveat", "fork", "vfork", "clone", "clone3"].contains(&name)
    {
        return true;
    }
    if blocked_perms.contains(&&Permission::NetworkOutbound) && NETWORK_SYSCALLS.contains(&name) {
        return true;
    }
    false
}

