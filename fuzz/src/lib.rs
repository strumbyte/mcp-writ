//! Shared harness for the boundary fuzz targets.
//!
//! Every binary under `fuzz_targets/` is one fuzz target: it maps `noprop`
//! draws into the byte input of a `mcp_writ::fuzz` entry point — the
//! code path that first interprets attacker-controlled data. A
//! target's *input* is one byte vector; parameters a case needs
//! (frame caps, intercept flags, forwarded names) are decoded from
//! its head, so a saved crash file replays verbatim via `--replay`.
//!
//! `noprop` does not shrink failing inputs — the crash artifact keeps
//! the raw bytes plus the seeded run report, and minimizing a witness
//! into a unit test is a manual step (guide §8).

use std::cell::RefCell;
use std::path::{Path, PathBuf};

/// Environment variable pinning the run seed — hex or decimal; the
/// failure report prints `0x..` and this parser accepts it verbatim.
pub const SEED_ENV: &str = "MCP_WRIT_FUZZ_SEED";

/// Parsed command-line/env knobs shared by every target.
pub struct Args {
    /// Accepted-case budget handed to `Runner::run`.
    pub cases: usize,
    pub seed: u64,
    /// Directory crash artifacts (`<target>.bin` + `<target>.txt`) go.
    pub crash_dir: PathBuf,
    /// Replay one recorded crash input instead of running cases.
    pub replay: Option<PathBuf>,
}

/// Parse `<target> [--cases N] [--seed HEX|DEC] [--crash-dir DIR]
/// [--replay FILE]`.
pub fn parse_args(target: &str) -> Args {
    let mut cases = 20_000usize;
    let mut seed: Option<u64> = None;
    let mut crash_dir = PathBuf::from("fuzz-artifacts");
    let mut replay = None;
    let mut it = std::env::args().skip(1);
    while let Some(a) = it.next() {
        match a.as_str() {
            "--cases" => match it.next().and_then(|v| v.parse().ok()) {
                Some(n) => cases = n,
                None => usage_fail(target, "--cases needs an integer"),
            },
            "--seed" => match it.next() {
                Some(v) => match parse_seed(&v) {
                    Ok(s) => seed = Some(s),
                    Err(e) => usage_fail(target, &e),
                },
                None => usage_fail(target, "--seed needs a value"),
            },
            "--crash-dir" => match it.next() {
                Some(v) => crash_dir = PathBuf::from(v),
                None => usage_fail(target, "--crash-dir needs a path"),
            },
            "--replay" => match it.next() {
                Some(v) => replay = Some(PathBuf::from(v)),
                None => usage_fail(target, "--replay needs a path"),
            },
            "--help" | "-h" => {
                usage(target);
                std::process::exit(0);
            }
            other => usage_fail(target, &format!("unknown argument {other}")),
        }
    }
    let seed = match seed {
        Some(s) => s,
        None => noprop::seed_from_env_or_time(SEED_ENV)
            .unwrap_or_else(|e| usage_fail(target, &e.to_string())),
    };
    Args {
        cases,
        seed,
        crash_dir,
        replay,
    }
}

/// Decimal or `0x`-hex seed, `_` separators allowed — the same spellings
/// `noprop::seed_from_env_or_time` accepts.
fn parse_seed(raw: &str) -> Result<u64, String> {
    let t = raw.trim();
    let (radix, digits) = match t.strip_prefix("0x") {
        Some(rest) => (16, rest),
        None => (10, t),
    };
    let cleaned: String = digits.chars().filter(|c| *c != '_').collect();
    u64::from_str_radix(&cleaned, radix)
        .map_err(|e| format!("bad seed {raw:?}: {e} (decimal or 0x-hex)"))
}

fn usage(target: &str) {
    eprintln!(
        "usage: {target} [--cases N] [--seed HEX|DEC] [--crash-dir DIR] [--replay FILE]\n\
         env:  {SEED_ENV}=0x.. pins the seed — a failure report prints one to paste."
    );
}

fn usage_fail(target: &str, msg: &str) -> ! {
    eprintln!("{target}: {msg}");
    usage(target);
    std::process::exit(2);
}

/// Drive `property` over `args.cases` generated byte inputs.
///
/// `gen` draws one case's input; `property` runs the boundary entry
/// point and asserts. `gates` runs once after a fully-passing run —
/// the noprop coverage-gate pattern — and returns a coverage report
/// line for the log. On any failure the last generated input lands in
/// `<crash-dir>/<name>.bin` next to a `<name>.txt` run report.
pub fn run<G, F, C>(name: &str, args: &Args, sample_input: G, property: F, gates: C) -> i32
where
    G: Fn(&mut noprop::TestCaseContext) -> Vec<u8>,
    F: Fn(&[u8]),
    C: FnOnce() -> String,
{
    if let Some(path) = &args.replay {
        return match std::fs::read(path) {
            Ok(data) => {
                property(&data);
                println!("[{name}] replay ok: {}", path.display());
                0
            }
            Err(e) => {
                eprintln!("[{name}] cannot read {}: {e}", path.display());
                2
            }
        };
    }
    println!("[{name}] cases={} seed={:#018x}", args.cases, args.seed);
    let last: RefCell<Vec<u8>> = RefCell::new(Vec::new());
    let mut runner = noprop::Runner::new(args.seed);
    let outcome = runner.run(args.cases, |ctx| {
        {
            let mut slot = last.borrow_mut();
            *slot = sample_input(ctx);
            property(&slot);
        }
        Ok(())
    });
    match outcome {
        Ok(()) => {
            let st = runner.stats();
            println!(
                "[{name}] {} cases passed (rejected {}, samples {})",
                st.accepted_cases, st.rejected_cases, st.total_samples
            );
            match std::panic::catch_unwind(std::panic::AssertUnwindSafe(gates)) {
                Ok(report) => {
                    println!("[{name}] coverage: {report}");
                    0
                }
                Err(payload) => {
                    let msg = panic_message(payload.as_ref());
                    fail(
                        name,
                        args,
                        &last.into_inner(),
                        &format!("coverage gate: {msg}"),
                    );
                    1
                }
            }
        }
        Err(e) => {
            fail(name, args, &last.into_inner(), &e.to_string());
            eprintln!("{e}");
            1
        }
    }
}

fn panic_message(payload: &(dyn std::any::Any + Send)) -> String {
    if let Some(s) = payload.downcast_ref::<String>() {
        s.clone()
    } else if let Some(s) = payload.downcast_ref::<&str>() {
        (*s).to_string()
    } else {
        "non-string panic".to_string()
    }
}

/// Write `<name>.bin` (the exact failing input — `--replay` it) and
/// `<name>.txt` (seed, budget, replay hint) under `args.crash_dir`.
fn fail(name: &str, args: &Args, input: &[u8], detail: &str) {
    // Shell-quote the replay path so a crash dir containing spaces still
    // parses as one argument; escape `\` first so it cannot eat the
    // closing quote, then the double-quote metacharacters.
    let bin = format!(
        "\"{}\"",
        args.crash_dir
            .join(format!("{name}.bin"))
            .display()
            .to_string()
            .replace('\\', "\\\\")
            .replace('"', "\\\"")
            .replace('$', "\\$")
            .replace('`', "\\`")
    );
    let report = format!(
        "target: {name}\nseed: {:#018x}\ncases: {}\ndetail: {detail}\n\n\
         replay: cargo run --release --manifest-path fuzz/Cargo.toml --bin {name} -- --replay {bin}\n\
         rerun:  {SEED_ENV}={:#018x} cargo run --release --manifest-path fuzz/Cargo.toml --bin {name} -- --cases {}\n",
        args.seed, args.cases, args.seed, args.cases
    );
    match write_crash(&args.crash_dir, name, input, &report) {
        Ok(dir) => eprintln!("[{name}] FAILED — artifacts in {}", dir.display()),
        Err(e) => eprintln!("[{name}] FAILED — could not write artifacts: {e}\n{report}"),
    }
}

fn write_crash(dir: &Path, name: &str, input: &[u8], report: &str) -> std::io::Result<PathBuf> {
    std::fs::create_dir_all(dir)?;
    std::fs::write(dir.join(format!("{name}.bin")), input)?;
    std::fs::write(dir.join(format!("{name}.txt")), report)?;
    Ok(dir.to_path_buf())
}
